#!/usr/bin/env python3
"""Generate FieldScriptletUpgradeTestData.xml with a target count of upgrade objects."""

from __future__ import annotations

import argparse
from pathlib import Path

RULES = ("FSU Test Rule Alpha", "FSU Test Rule Beta", "FSU Test Rule Gamma")
UPGRADE_TYPES = ("Form", "Workflow", "Application", "Bundle", "WorkItem", "WorkflowCase")
TARGET_TOTAL = 3000

HEADER = """<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE sailpoint PUBLIC "sailpoint.dtd" "sailpoint.dtd">
<!--
  Scaled test data for FieldScriptletUpgradeExecutorTests and integration runs.
  Generated by scripts/generate_field_scriptlet_upgrade_test_data.py — do not hand-edit at scale.
-->
<sailpoint>
"""

RULES_BLOCK = """  <Rule language="beanshell" name="FSU Test Rule Alpha">
    <Source><![CDATA[return true;]]></Source>
  </Rule>
  <Rule language="beanshell" name="FSU Test Rule Beta">
    <Source><![CDATA[return false;]]></Source>
  </Rule>
  <Rule language="beanshell" name="FSU Test Rule Gamma">
    <Source><![CDATA[return identity != null;]]></Source>
  </Rule>
"""

FOOTER = "</sailpoint>\n"


def variant_for_index(n: int) -> int:
    return (n - 1) % 5


def rule_for_variant(variant: int) -> str:
    if variant in (0, 3):
        return RULES[0]
    if variant in (1, 4):
        return RULES[1]
    return RULES[2]


def embedded_fields(n: int, tag: str, indent: str) -> str:
    """Field block shared by embedded forms (workflows, apps, etc.)."""
    variant = variant_for_index(n)
    rule = rule_for_variant(variant)
    script_ret = f"FSU-{tag}{n}"
    lines = [
        f'{indent}<Field name="script_field" displayName="script_field" '
        f'value="script:return &quot;{script_ret}&quot;;"/>',
        f'{indent}<Field name="rule_field" displayName="rule_field" value="rule:{rule}"/>',
        f'{indent}<Field name="ref_field" displayName="ref_field" value="ref:launcher"/>',
        f'{indent}<Field name="string_field" displayName="string_field" '
        f'value="string:Display text for {tag}{n}"/>',
        f'{indent}<Field name="plain_field" displayName="plain_field" value="Plain value not converted"/>',
        f'{indent}<Field name="static_type" displayName="static_type" type="string"/>',
    ]
    if variant in (1, 3):
        lines.append(
            f'{indent}<Field name="neg_script_field" displayName="neg_script_field" '
            f'value="!script:isTrue(active)"/>'
        )
    if variant == 1:
        lines.append(
            f'{indent}<Field name="neg_rule_field" displayName="neg_rule_field" '
            f'value="!rule:{rule}"/>'
        )
    lines.extend(
        [
            f'{indent}<Field name="modern_script" displayName="modern_script">',
            f'{indent}  <Script><Source>return "already modern";</Source></Script>',
            f"{indent}</Field>",
            f'{indent}<Field name="ref_identity" displayName="ref_identity" value="ref:identityName"/>',
        ]
    )
    return "\n".join(lines)


def form_standalone(n: int) -> str:
    variant = variant_for_index(n)
    rule = rule_for_variant(variant)
    lines = [
        f'  <Form name="FSU Test Form {n}" type="Workflow">',
        "    <Section>",
        f'      <Field name="script_field" displayName="script_field" '
        f'value="script:return &quot;FSU-{n}&quot;;"/>',
        f'      <Field name="rule_field" displayName="rule_field" value="rule:{rule}"/>',
        '      <Field name="ref_field" displayName="ref_field" value="ref:launcher"/>',
        f'      <Field name="string_field" displayName="string_field" '
        f'value="string:Display text for {n}"/>',
        '      <Field name="plain_field" displayName="plain_field" value="Plain value not converted"/>',
        '      <Field name="static_type" displayName="static_type" type="string"/>',
    ]
    if n == 1:
        lines.append(
            '      <Field name="legacy_call_probe" displayName="legacy_call_probe" value="call:noopProbe"/>'
        )
    if variant in (1, 3):
        lines.append(
            '      <Field name="neg_script_field" displayName="neg_script_field" '
            'value="!script:isTrue(active)"/>'
        )
    if variant == 1:
        lines.append(
            f'      <Field name="neg_rule_field" displayName="neg_rule_field" value="!rule:{rule}"/>'
        )
    lines.extend(
        [
            '      <Field name="modern_script" displayName="modern_script">',
            '        <Script><Source>return "already modern";</Source></Script>',
            "      </Field>",
            '      <Field name="ref_identity" displayName="ref_identity" value="ref:identityName"/>',
            "    </Section>",
            "  </Form>",
        ]
    )
    return "\n".join(lines)


def workflow_object(n: int) -> str:
    fields = embedded_fields(n, "W", "        ")
    return f"""  <Workflow name="FSU Test Workflow {n}">
    <Step name="FSU Test Step {n}">
      <Approval owner="spadmin" mode="serial">
      <Form name="FSU Test Embedded Form W{n}" type="Workflow">
        <Section>
{fields}
        </Section>
      </Form>
      </Approval>
    </Step>
  </Workflow>
"""


def application_object(n: int) -> str:
    fields = embedded_fields(n, "A", "        ")
    return f"""  <Application name="FSU Test Application {n}" type="Generic">
    <Attributes><Map><entry key="testData" value="fieldScriptletUpgrade"/></Map></Attributes>
    <ProvisioningForms>
      <Form name="FSU Test Embedded Form A{n}" type="Workflow">
        <Section>
{fields}
        </Section>
      </Form>
    </ProvisioningForms>
  </Application>
"""


def bundle_object(n: int) -> str:
    fields = embedded_fields(n, "B", "        ")
    return f"""  <Bundle name="FSU Test Bundle {n}">
    <ProvisioningForms>
      <Form name="FSU Test Embedded Form B{n}" type="Workflow">
        <Section>
{fields}
        </Section>
      </Form>
    </ProvisioningForms>
  </Bundle>
"""


def workitem_object(n: int) -> str:
    fields = embedded_fields(n, "WI", "            ")
    return f"""  <WorkItem name="FSU Test WorkItem {n}" type="Form">
    <Attributes>
      <Map>
        <entry key="workItemForm"><value>
          <Form name="FSU Test Embedded Form WI{n}" type="Workflow">
            <Section>
{fields}
            </Section>
          </Form>
        </value>
        </entry>
      </Map>
    </Attributes>
  </WorkItem>
"""


def workflow_case_object(n: int) -> str:
    fields = embedded_fields(n, "C", "            ")
    return f"""  <WorkflowCase name="FSU Test WorkflowCase {n}">
    <Workflow name="FSU Test Case Workflow {n}">
      <Step name="Case Step {n}">
        <Approval owner="spadmin">
          <Form name="FSU Test Embedded Form C{n}" type="Workflow">
            <Section>
{fields}
            </Section>
          </Form>
        </Approval>
      </Step>
    </Workflow>
  </WorkflowCase>
"""


GENERATORS = {
    "Form": form_standalone,
    "Workflow": workflow_object,
    "Application": application_object,
    "Bundle": bundle_object,
    "WorkItem": workitem_object,
    "WorkflowCase": workflow_case_object,
}


def per_type_count(total: int, type_count: int) -> list[int]:
    base = total // type_count
    remainder = total % type_count
    counts = [base] * type_count
    for i in range(remainder):
        counts[i] += 1
    return counts


def generate(total: int) -> str:
    if total % len(UPGRADE_TYPES) != 0:
        raise ValueError(f"total {total} must be divisible by {len(UPGRADE_TYPES)} upgrade types")
    per_type = total // len(UPGRADE_TYPES)
    parts = [HEADER, RULES_BLOCK]
    for type_name in UPGRADE_TYPES:
        gen = GENERATORS[type_name]
        for i in range(1, per_type + 1):
            parts.append(gen(i))
            parts.append("")
    parts.append(FOOTER)
    return "\n".join(parts)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--total", type=int, default=TARGET_TOTAL)
    parser.add_argument(
        "--out",
        type=Path,
        action="append",
        default=[
            Path("src/config/FieldScriptletUpgradeTestData.xml"),
            Path("test/sailpoint/task/FieldScriptletUpgradeTestData.xml"),
        ],
    )
    args = parser.parse_args()
    content = generate(args.total)
    for path in args.out:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"Wrote {path} ({args.total} upgrade objects, {len(content):,} bytes)")


if __name__ == "__main__":
    main()
